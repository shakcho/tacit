import { readFileSync } from "node:fs";
import { resolve } from "node:path";

import { describe, expect, it } from "vitest";

import type { AuthorizationAction, AuthorizationSnapshot } from "@/api/generated/models";
import { createPresentationAbility } from "@/auth/abilities";

describe("createPresentationAbility", () => {
  it("copies only allowed exact server decisions", () => {
    const first = "resource/org_0123456789abcdef0123456789abcdef/meeting/mtg_first";
    const second = "resource/org_0123456789abcdef0123456789abcdef/meeting/mtg_second";
    const snapshot: AuthorizationSnapshot = {
      policyRevision: "tacit-authorization-v1",
      decisions: [
        { action: "read", allowed: true, resource: "meeting", scope: "resource", subject: first },
        { action: "update", allowed: false, resource: "meeting", scope: "resource", subject: first },
      ],
    };

    const ability = createPresentationAbility(snapshot);

    expect(ability.can("read", first)).toBe(true);
    expect(ability.can("update", first)).toBe(false);
    expect(ability.can("read", second)).toBe(false);
  });

  it("denies everything for an empty snapshot", () => {
    const ability = createPresentationAbility({ decisions: [], policyRevision: "tacit-authorization-v1" });
    expect(ability.can("read", "context/org_0123456789abcdef0123456789abcdef/organization")).toBe(false);
  });

  it("matches the decision snapshots generated by Go", () => {
    const path = resolve(process.cwd(), "../../internal/access/testdata/presentation.json");
    const fixture = JSON.parse(readFileSync(path, "utf8")) as {
      snapshots: Array<AuthorizationSnapshot & {
        assertions: Array<{ action: AuthorizationAction; allowed: boolean; subject: string }>;
        name: string;
      }>;
    };

    for (const snapshot of fixture.snapshots) {
      const ability = createPresentationAbility(snapshot);
      for (const assertion of snapshot.assertions) {
        expect(ability.can(assertion.action, assertion.subject), snapshot.name).toBe(assertion.allowed);
      }
    }
  });
});
