import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, extname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repositoryRoot = resolve(packageRoot, "..", "..");
const documentRoot = join(repositoryRoot, "apps", "web", "src");
const outputPath = join(packageRoot, "src", "generated", "operations.ts");
const checkOnly = process.argv.includes("--check");

async function graphqlFiles(directory) {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await graphqlFiles(path));
    else if (extname(entry.name) === ".graphql") files.push(path);
  }
  return files;
}

const documents = [];
for (const file of await graphqlFiles(documentRoot)) {
  const source = (await readFile(file, "utf8")).trim();
  const matches = [...source.matchAll(/\b(query|mutation|subscription)\s+([A-Z][A-Za-z0-9_]*)\b/gu)];
  for (const match of matches) {
    const name = match[2];
    if (name !== undefined) documents.push({ name, source, sourcePath: relative(repositoryRoot, file) });
  }
}

documents.sort((left, right) => left.name.localeCompare(right.name));

const entries = documents.map(({ name, source }) => `  ${JSON.stringify(name)}: ${JSON.stringify(source)},`).join("\n");
const generated = `// Code generated by packages/contracts/scripts/generate-documents.mjs. DO NOT EDIT.\n\nexport const operations: Readonly<Record<string, string>> = Object.freeze({\n${entries}\n});\n`;

if (checkOnly) {
  const current = await readFile(outputPath, "utf8");
  if (current !== generated) {
    console.error("Generated GraphQL operation registry is stale. Run pnpm generate.");
    process.exitCode = 1;
  } else {
    console.log(`Verified ${documents.length} generated GraphQL operation(s).`);
  }
} else {
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, generated);
  console.log(`Generated ${documents.length} GraphQL operation(s) from ${documentRoot}.`);
}
